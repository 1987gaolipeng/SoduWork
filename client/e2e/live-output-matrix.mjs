// Explicit live acceptance: actual desktop UI, installed adapter and model.
// Each adapter uses its own synthetic workspace. Never run on a user's draft.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {CdpPage,listPages} from './lib/cdp.mjs';
const [mode='status',adapter='pi',run='']=process.argv.slice(2);
const supported=['pi','codex-harness','opencode','claude','codex','qwen','dsh'];
assert.ok(supported.includes(adapter));
assert.ok(!run || /^[a-z0-9-]{1,64}$/.test(run),'Invalid acceptance run label');
const out=path.join(fileURLToPath(new URL('../../outputs/md-output-live-matrix/',import.meta.url)),run);
fs.mkdirSync(out,{recursive:true});
const receipt=path.join(out,'result-'+adapter+'.json');
const p=await CdpPage.connect((await listPages(9348)).find(x=>x.url.includes('/desk.html')));
const delay=ms=>new Promise(r=>setTimeout(r,ms));
async function state(){return p.run(async()=>{const i=NativeChat.sessionInfo();const s=i.ref?(await soduWorkAPI.conversationSession.snapshot(i.ref)).snapshot:null;return {info:i,status:s?.status,text:s?.statusText,running:s?.execution?.running,pending:s?.pendingUi||null,draft:document.querySelector('#nchatInput')?.value?.length,tools:s?.tools?.map(t=>({name:t.name,state:t.state,isError:t.isError})),workbench:ChatWorkbench.state()};});}
async function click(selector){const point=await p.run(selector=>{const e=document.querySelector(selector);if(!e)throw Error('Missing '+selector);e.scrollIntoView({block:'center'});const r=e.getBoundingClientRect();const point={x:r.x+r.width/2,y:r.y+r.height/2};if(!e.contains(document.elementFromPoint(point.x,point.y)))throw Error('Occluded '+selector);return point;},selector);for(const type of ['mousePressed','mouseReleased'])await p.call('Input.dispatchMouseEvent',{type,...point,button:'left',clickCount:1});}
async function shot(suffix){const shot=await p.call('Page.captureScreenshot',{format:'png'});fs.writeFileSync(path.join(out,adapter+'-'+suffix+'.png'),Buffer.from(shot.data,'base64'));}
try{
 if(mode==='retry'){
  const old=JSON.parse(fs.readFileSync(receipt,'utf8')),current=await state();
  assert.equal(current.info.sessionId,old.sessionId);assert.ok(!current.running&&!current.pending&&!current.draft);
  assert.equal(fs.existsSync(path.join(old.cwd,'交付报告.md')),false,'Do not replay a successful write');
  fs.writeFileSync(receipt,JSON.stringify({...old,failure:current.text},null,2));
  fs.renameSync(receipt,path.join(out,'result-'+adapter+'-attempt-'+Date.now()+'.json'));
  await p.run(async ref=>{soduWorkAPI.conversationSession.close(ref);NativeChat.reset();},current.info.ref);
  console.log('Failed test session closed; ready for a new attempt.');
 }else
 if(mode==='start'){
  assert.equal(fs.existsSync(receipt),false,'Existing live test record; do not repeat model calls accidentally');
  const current=await state();assert.ok(!current.running&&!current.pending&&!current.draft,'Current conversation is busy or has a draft');
  const cwd=path.join(out,'work-'+adapter);fs.mkdirSync(cwd,{recursive:true});
  assert.equal(fs.existsSync(path.join(cwd,'交付报告.md')),false,'Output must be generated by the actual adapter');
  const options={cwd,adapterId:adapter,...(['pi','codex-harness','opencode','qwen'].includes(adapter)?{accessMode:'standard'}:{})};
  const opened=await p.run(async options=>{NativeChat.reset();return NativeChat.enter('',null,options);},options);
  assert.equal(opened,true,'Could not open live adapter');
  const initial=await state();assert.equal(initial.info.adapterId,adapter);
  // NativeChat creates the session; the public page entry also reveals it
  // when the freshly restarted desktop is still showing its welcome page.
  assert.equal(await p.run(async id=>openComposePanel({chatId:id,source:'history'}),initial.info.sessionId),true);
  fs.writeFileSync(receipt,JSON.stringify({adapter,cwd,sessionId:initial.info.sessionId,ref:initial.info.ref,started:new Date().toISOString()},null,2));
  await click('#nchatInput');
  await p.call('Input.insertText',{text:`这是 SoduWork 文件交付验收。只在当前工作目录创建 UTF-8 文件“交付报告.md”，内容为“# 文件交付验收\n\n底座：${adapter}\n\n验证标识：SODUWORK-MD-E2E-20260930”。使用真实文件工具完成；不要检索、不要发消息、不修改其他文件。最后只回答：已生成 \`交付报告.md\`。`});
  await p.call('Input.dispatchKeyEvent',{type:'keyDown',key:'Enter',code:'Enter',windowsVirtualKeyCode:13});
  await p.call('Input.dispatchKeyEvent',{type:'keyUp',key:'Enter',code:'Enter',windowsVirtualKeyCode:13});
  console.log(JSON.stringify(await state()));
 }else{
  const record=JSON.parse(fs.readFileSync(receipt,'utf8'));
  const current=await state();assert.equal(current.info.sessionId,record.sessionId,'UI changed to a different conversation');
  if(mode==='allow-file'){
   const approval=current.pending;assert.ok(approval,'No pending approval');
   assert.equal(approval.target,path.join(record.cwd,'交付报告.md'));
   const changes=approval.arguments?.changes;assert.equal(changes?.length,1);assert.equal(changes[0].path,approval.target);
   assert.ok(String(changes[0].newText).includes('SODUWORK-MD-E2E-20260930'));assert.equal(changes[0].oldText,null);
   await click('[data-ui-answer="permission"][data-ui-value="once"]');console.log('Approved the isolated report file only.');
  }else if(mode==='verify'){
   assert.equal(current.running,false,'Model still running');assert.equal(current.pending,null,'Awaiting approval');
   assert.equal(current.status,'idle',current.text);
   const file=path.join(record.cwd,'交付报告.md');const content=fs.readFileSync(file,'utf8');assert.match(content,/SODUWORK-MD-E2E-20260930/);assert.ok(content.includes(adapter));
   const view=await p.run(()=>({open:ChatWorkbench.state().open,title:document.querySelector('.ncw-markdown h1')?.textContent,links:[...document.querySelectorAll('.nmsg.ai [data-open-app]')].filter(n=>n.textContent==='交付报告.md').map(n=>n.dataset.openApp)}));
   assert.ok(view.links.length,'Filename is not marked clickable');assert.equal(view.open,true,'Markdown did not auto-open');assert.equal(view.title,'文件交付验收');
   await shot('generated');await click('[data-wb-close]');await click('[data-open-app="'+view.links.at(-1)+'"]');await delay(350);
   assert.equal((await state()).workbench.open,true);
   await p.run(async ref=>{await soduWorkAPI.conversationSession.close(ref);NativeChat.reset();},record.ref);
   const reopened=await p.run(async id=>NativeChat.enter('',id),record.sessionId);assert.equal(reopened,true);
   await delay(500);
   const link=await p.run(()=>[...document.querySelectorAll('.nmsg.ai [data-open-app]')].find(n=>n.textContent==='交付报告.md')?.dataset.openApp);assert.ok(link,'Historical output link missing');
   await click('[data-open-app="'+link+'"]');await delay(350);
   assert.equal(await p.run(()=>document.querySelector('.ncw-markdown h1')?.textContent),'文件交付验收');
   await shot('reopened');Object.assign(record,{ok:true,completed:new Date().toISOString(),tools:current.tools,checks:['real file generation','inline filename link','automatic Markdown pane','actual mouse click','native handle close','archive reopen and Markdown read']});fs.writeFileSync(receipt,JSON.stringify(record,null,2));console.log(JSON.stringify(record));
  }else console.log(JSON.stringify(current,null,2));
 }
}finally{p.close();}
